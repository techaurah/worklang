"""The futures demo: after-hours missed lead (DESIGN.md, build step 6).

The demo is a static page with precomputed outputs, because there is
no hosted inference at v0. This module holds everything the page
needs: the authored scenario prefixes, the sampling configuration,
the sampler that produces the committed data file, and the page
renderer. scripts/sample_futures.py is the thin CLI over it.

The scenario is the design's: a lead messages a med spa at 21:47 on
Instagram, outside business hours. Nobody replies until morning. What
usually happens next? Two authored prefixes (labelled as authored
examples, not corpus data, exactly as the design requires):

- without-reply: BOS, vertical med-spa, one enquiry event (channel
  instagram, stage NEW, latency none), then nothing.
- with-reply: the same prefix with one instant automated reply event
  inserted, the counterfactual.

Sampling configuration is page configuration, stated on the page and
recorded in the data file, not a hidden default: 200 futures per
prefix at temperature 1.0, the temperature the step 5 calibration was
measured at, capped at 64 new events per future (the calibration cap).

Model weights: build step 5 proved the training run is bit-for-bit
reproducible (two same-seed runs, largest metric delta 0.0), but it
did not save a weights file. ensure_trained_model closes that gap:
if the weights file exists it is loaded; if not, the model is trained
with exactly the step 5 configuration (TrainConfig defaults, corpus
v0 train split) and the weights are saved first. Either way the data
file records the counted parameter total and the training
configuration, so what sampled the futures is never ambiguous.

Truncation rule, same as calibration: a future that reaches the cap
without an outcome event is counted as truncated, listed in the data
file as the string "truncated", and excluded from the outcome
distribution; it never silently becomes an outcome. Shares are
percentages of completed futures, and the data file says so.

The caveat is data, not decoration: CAVEAT below is stored in the
data file and rendered by the page at the same visual weight as the
headline numbers, per the design rule. The demo's shares are model
behaviour on a synthetic corpus, not measured business statistics.
"""

from __future__ import annotations

import dataclasses
import json
from collections import Counter
from collections.abc import Sequence
from pathlib import Path

import torch

from .errors import DemoError
from .mini import (
    MiniConfig,
    TrainConfig,
    WorkLangMini,
    count_parameters,
    sample_future,
    train_model,
)
from .schema import Event, Trace
from .vocab import OUTCOME_CLASSES

# Sampling configuration for the demo page. Stated on the page and
# recorded in demo-data.json; changing these changes the demo.
SAMPLES_PER_PREFIX = 200
TEMPERATURE = 1.0
SEED = 20261105
MAX_NEW_EVENTS = 64

# The model the demo samples from, and where its weights live.
MODEL_NAME = "worklang-mini"
WEIGHTS_FILENAME = "worklang-mini-v0.pt"
DATA_FILENAME = "demo-data.json"
PAGE_FILENAME = "index.html"
TEMPLATE_FILENAME = "index.template.html"
DATA_PLACEHOLDER = "/*__WORKLANG_DEMO_DATA__*/"

OUTCOME_VALUES = tuple(c for c in OUTCOME_CLASSES if c != "none")
TRUNCATED = "truncated"

CAVEAT = (
    "Read this first: worklang-mini was trained only on synthetic "
    "traces generated by TechAura's own simulators (QualBench agent "
    "runs and the LeadPipe demo lifecycle). It has never seen a real "
    "business, a real lead, or real customer data. The percentages "
    "on this page are model behaviour, shares of trajectories the "
    "model sampled, not measured business statistics, and they "
    "describe what the model expects inside its simulators' world, "
    "not what will happen in yours."
)

SCENARIO_TITLE = "The after-hours missed lead"
SCENARIO_STORY = (
    "A lead messages a med spa at 21:47 on Instagram, outside "
    "business hours. Nobody replies until morning. What usually "
    "happens next? WorkLang answers by sampling futures: it continues "
    "the trace from this prefix, one sampled event at a time, until "
    "each sampled future reaches its outcome, then reports the share "
    "of sampled trajectories behind each outcome class. The second "
    "panel runs the counterfactual prefix, the same message answered "
    "at once by an automated reply."
)

DEMO_VERTICAL = "med-spa"


def _enquiry_event() -> Event:
    return Event(
        seq=0,
        family="enquiry",
        channel="instagram",
        score_band="none",
        latency_band="none",
        stage="NEW",
        tool="none",
        outcome_class="none",
    )


def _reply_event() -> Event:
    return Event(
        seq=1,
        family="reply",
        channel="instagram",
        score_band="none",
        latency_band="instant",
        stage="NEW",
        tool="none",
        outcome_class="none",
    )


@dataclasses.dataclass(frozen=True)
class DemoPrefix:
    """One authored demo prefix: events plus their plain reading."""

    prefix_id: str
    label: str
    description: str
    events: tuple[Event, ...]
    plain_lines: tuple[str, ...]


PREFIXES: tuple[DemoPrefix, ...] = (
    DemoPrefix(
        prefix_id="without-reply",
        label="No reply until morning",
        description=(
            "The authored prefix is the message and nothing else: "
            "BOS, the med-spa vertical token, and one enquiry event "
            "(channel instagram, stage NEW, latency none). The model "
            "continues from the silence."
        ),
        events=(_enquiry_event(),),
        plain_lines=(
            "21:47, a lead messages the med spa on Instagram: "
            "enquiry, channel instagram, stage NEW, no reply yet.",
        ),
    ),
    DemoPrefix(
        prefix_id="with-reply",
        label="Instant automated reply",
        description=(
            "The counterfactual prefix: the same enquiry, plus one "
            "reply event with latency instant, an automated answer "
            "sent at once. Everything after that is still sampled."
        ),
        events=(_enquiry_event(), _reply_event()),
        plain_lines=(
            "21:47, a lead messages the med spa on Instagram: "
            "enquiry, channel instagram, stage NEW.",
            "Seconds later, an automated reply answers: reply, "
            "channel instagram, latency instant, stage NEW.",
        ),
    ),
)


def prefix_by_id(prefix_id: str) -> DemoPrefix:
    for prefix in PREFIXES:
        if prefix.prefix_id == prefix_id:
            return prefix
    raise DemoError(f"unknown demo prefix id: {prefix_id!r}")


def save_weights(
    model: WorkLangMini, path: Path, *, provenance: str
) -> None:
    """Save the mini weights plus the config needed to rebuild it."""
    torch.save(
        {
            "model_name": MODEL_NAME,
            "config": dataclasses.asdict(model.config),
            "parameter_count": count_parameters(model),
            "provenance": provenance,
            "state_dict": model.state_dict(),
        },
        path,
    )


def load_weights(path: Path) -> tuple[WorkLangMini, dict]:
    """Load a saved mini; returns the model and the file's metadata."""
    payload = torch.load(path, map_location="cpu", weights_only=True)
    config = MiniConfig(**payload["config"])
    model = WorkLangMini(config)
    model.load_state_dict(payload["state_dict"])
    model.eval()
    counted = count_parameters(model)
    if counted != payload["parameter_count"]:
        raise DemoError(
            f"weights file {path} records {payload['parameter_count']} "
            f"parameters but the loaded model counts {counted}"
        )
    metadata = {
        "model_name": payload["model_name"],
        "config": payload["config"],
        "parameter_count": counted,
        "provenance": payload["provenance"],
    }
    return model, metadata


def ensure_trained_model(
    weights_path: Path,
    *,
    train_traces: Sequence[Trace] | None = None,
    config: MiniConfig | None = None,
    train_config: TrainConfig | None = None,
) -> tuple[WorkLangMini, dict]:
    """Load the trained mini, training and saving it first if needed.

    Training uses the step 5 configuration (TrainConfig defaults)
    on the traces given, which the caller takes from the corpus v0
    train split; step 5 proved that configuration reproduces the
    evaluated model exactly (largest metric delta 0.0 across two
    runs). The returned metadata records which path was taken.
    """
    if weights_path.exists():
        model, metadata = load_weights(weights_path)
        metadata["weights_source"] = f"loaded from {weights_path.name}"
        return model, metadata
    if train_traces is None:
        raise DemoError(
            f"no weights file at {weights_path} and no training "
            "traces were given to train one"
        )
    tcfg = train_config or TrainConfig()
    provenance = (
        "Trained by the demo sampler with the step 5 configuration "
        f"(epochs {tcfg.epochs}, lr {tcfg.lr}, batch size "
        f"{tcfg.batch_size}, weight decay {tcfg.weight_decay}, seed "
        f"{tcfg.seed}, CPU) on the corpus v0 train split "
        f"({len(train_traces)} traces); the same configuration "
        "scripts/train_mini.py evaluated in results/mini-v0.json, "
        "where two same-seed runs agreed exactly."
    )
    model, _info = train_model(
        train_traces, config=config, train_config=tcfg
    )
    weights_path.parent.mkdir(parents=True, exist_ok=True)
    save_weights(model, weights_path, provenance=provenance)
    metadata = {
        "model_name": MODEL_NAME,
        "config": dataclasses.asdict(model.config),
        "parameter_count": count_parameters(model),
        "provenance": provenance,
        "weights_source": (
            f"trained in this run and saved to {weights_path.name}"
        ),
    }
    return model, metadata


def sample_prefix_futures(
    model: WorkLangMini,
    prefix_index: int,
    prefix: DemoPrefix,
    *,
    samples: int = SAMPLES_PER_PREFIX,
    temperature: float = TEMPERATURE,
    seed: int = SEED,
    max_new_events: int = MAX_NEW_EVENTS,
) -> list[tuple[tuple[Event, ...], bool]]:
    """Sample futures for one prefix; returns (future, completed)."""
    futures: list[tuple[tuple[Event, ...], bool]] = []
    for sample_index in range(samples):
        sample_seed = seed * 1_000_003 + prefix_index * 10_007 + sample_index
        future, completed = sample_future(
            model,
            DEMO_VERTICAL,
            prefix.events,
            temperature=temperature,
            seed=sample_seed,
            max_new_events=max_new_events,
        )
        futures.append((future, completed))
    return futures


def _distribution(outcomes: Sequence[str]) -> dict:
    """Outcome counts and shares over completed futures only."""
    completed = [o for o in outcomes if o != TRUNCATED]
    counts = Counter(completed)
    total = len(completed)
    return {
        "base": (
            "shares are percentages of completed sampled futures; "
            "truncated futures are counted separately and excluded"
        ),
        "completed": total,
        "classes": {
            name: {
                "count": counts.get(name, 0),
                "share_percent": (
                    round(100.0 * counts.get(name, 0) / total, 1)
                    if total
                    else 0.0
                ),
            }
            for name in OUTCOME_VALUES
        },
    }


def _pick_examples(
    prefix: DemoPrefix,
    futures: Sequence[tuple[tuple[Event, ...], bool]],
    *,
    limit: int = 3,
) -> list[dict]:
    """Pick up to `limit` completed futures as page examples.

    Deterministic: one example per distinct outcome class first,
    classes ordered by sampled frequency (ties by outcome class
    order), then further examples in sampled order. Each example is
    the full trajectory (prefix events plus generated events) as
    event dicts, so the schema round trip test can rebuild and
    validate the whole trace.
    """
    completed = [future for future, done in futures if done]
    counts = Counter(f[-1].outcome_class for f in completed)
    ranked = sorted(
        counts,
        key=lambda name: (-counts[name], OUTCOME_VALUES.index(name)),
    )
    chosen: list[tuple[Event, ...]] = []
    used: set[int] = set()
    for name in ranked:
        if len(chosen) >= limit:
            break
        for index, future in enumerate(completed):
            if index not in used and future[-1].outcome_class == name:
                chosen.append(future)
                used.add(index)
                break
    for index, future in enumerate(completed):
        if len(chosen) >= limit:
            break
        if index not in used:
            chosen.append(future)
            used.add(index)
    return [
        {
            "outcome": future[-1].outcome_class,
            "prefix_event_count": len(prefix.events),
            "events": [
                event.to_dict()
                for event in tuple(prefix.events) + future
            ],
        }
        for future in chosen
    ]


def build_demo_data(
    model: WorkLangMini,
    model_metadata: dict,
    *,
    samples: int = SAMPLES_PER_PREFIX,
    temperature: float = TEMPERATURE,
    seed: int = SEED,
    max_new_events: int = MAX_NEW_EVENTS,
) -> dict:
    """Sample both prefixes and build the demo data document."""
    prefix_blocks = []
    for prefix_index, prefix in enumerate(PREFIXES):
        futures = sample_prefix_futures(
            model,
            prefix_index,
            prefix,
            samples=samples,
            temperature=temperature,
            seed=seed,
            max_new_events=max_new_events,
        )
        outcomes = [
            future[-1].outcome_class if completed else TRUNCATED
            for future, completed in futures
        ]
        prefix_blocks.append(
            {
                "id": prefix.prefix_id,
                "label": prefix.label,
                "description": prefix.description,
                "events": [event.to_dict() for event in prefix.events],
                "plain_lines": list(prefix.plain_lines),
                "sampled_outcomes": outcomes,
                "samples": len(outcomes),
                "truncated": outcomes.count(TRUNCATED),
                "distribution": _distribution(outcomes),
                "examples": _pick_examples(prefix, futures),
            }
        )
    return {
        "demo": "after-hours-missed-lead",
        "generated_by": "scripts/sample_futures.py",
        "model": {
            "name": model_metadata["model_name"],
            "parameter_count": model_metadata["parameter_count"],
            "config": model_metadata["config"],
            "weights_file": WEIGHTS_FILENAME,
            "weights_source": model_metadata["weights_source"],
            "provenance": model_metadata["provenance"],
            "evaluation_reference": (
                "results/mini-v0.json (held-out test split of corpus "
                "v0, step 4 harness protocol)"
            ),
        },
        "sampling": {
            "samples_per_prefix": samples,
            "temperature": temperature,
            "seed": seed,
            "max_new_events": max_new_events,
            "seed_scheme": (
                "per-sample seed = seed * 1000003 + prefix_index * "
                "10007 + sample_index; prefixes in page order"
            ),
        },
        "scenario": {
            "title": SCENARIO_TITLE,
            "story": SCENARIO_STORY,
            "vertical": DEMO_VERTICAL,
            "prefix_note": (
                "Both prefixes are authored examples, written for "
                "this demo. They are not corpus data and no real "
                "lead produced them."
            ),
        },
        "caveat": CAVEAT,
        "prefixes": prefix_blocks,
    }


def write_demo_data(data: dict, path: Path) -> None:
    path.write_text(
        json.dumps(data, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )


def render_page(data: dict, template: str) -> str:
    """Render the static page: the template plus the data, inlined.

    The page is a single self-contained HTML file: the demo data is
    embedded as JSON in the page itself, so opening the file makes
    no external requests and needs no server.
    """
    if DATA_PLACEHOLDER not in template:
        raise DemoError(
            f"page template is missing the data placeholder "
            f"{DATA_PLACEHOLDER!r}"
        )
    payload = json.dumps(data, indent=2, sort_keys=True)
    # Keep the JSON from closing the script element early.
    payload = payload.replace("</", "<\\/")
    return template.replace(DATA_PLACEHOLDER, payload, 1)


