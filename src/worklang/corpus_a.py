"""Corpus source A: generation, group-aware split, and corpus card.

Build step 2 of DESIGN.md (corpus plan, QualBench source). Generation
method, exactly as the design fixes it: run all 50 scenarios against
both shipped agents (reference-agent and naive-agent) through the
trace emitter, plus seeded variants. Variants come from seeded
parameter perturbation of scenario inputs; of the surfaces the design
lists (names, budgets, requested times, seed calendar busy blocks),
only the seed calendar busy blocks are structured data the loader
exposes as a value. Names, budgets, and requested times live inside
prose turns, which the loader treats as opaque strings, so perturbing
them would mean editing scenario content rather than perturbing an
input. Variant k therefore shifts every seeded busy block of the
scenario by one seeded whole-hour offset (layout preserved), and each
variant run is a real run of the perturbed scenario through the
unmodified runner and agents. Expected outcomes are never edited.

Splits: by trace, 80/10/10 train/validation/test, group-aware. A
group is one scenario (group id from the emitter: source plus
pack/name); every trace of a group, across both agents and all
variants, lands in exactly one split, so the test split measures
generalisation to unseen scenarios, not memorised variants. Groups
are shuffled with the split seed and cut 80/10/10 by group count;
because every group holds the same number of traces by construction,
the trace split is 80/10/10 as well. The seed is published in the
corpus card.

The corpus card is generated here from the built corpus; every number
in it is counted from the traces themselves.
"""

from __future__ import annotations

import copy
import dataclasses
import json
import random
from collections import Counter
from datetime import datetime, timedelta
from pathlib import Path
from typing import Any

from .qualbench_emitter import (
    AGENT_FILES,
    EMITTER_NAME,
    EMITTER_VERSION,
    LATENCY_DISTRIBUTIONS,
    default_qualbench_root,
    group_id_for,
    load_qualbench,
    run_and_emit,
    trace_seed_for,
)
from .schema import Trace, trace_to_json
from .tokenizer import encode_trace

DEFAULT_CORPUS_SEED = 20261104
DEFAULT_VARIANTS = 3
SPLIT_NAMES = ("train", "validation", "test")
SYNTHETIC_SENTENCE = (
    "100 percent synthetic, generated by TechAura's own simulators, "
    "contains no real customer data"
)

_VARIANT_OFFSETS_HOURS = (-3, -2, -1, 1, 2, 3)


def perturb_scenario(scenario: Any, variant: int, rng: random.Random) -> Any:
    """Return the variant of a scenario (variant 0 is the scenario).

    The only perturbation surface is the seed calendar's busy blocks:
    all blocks shift by one seeded whole-hour offset, preserving their
    layout. The scenario object itself is never mutated.
    """
    if variant == 0:
        return scenario
    seed_calendar = copy.deepcopy(scenario.seed_calendar or {})
    busy = seed_calendar.get("busy") or []
    if busy:
        offset = timedelta(hours=rng.choice(_VARIANT_OFFSETS_HOURS))
        shifted = []
        for block in busy:
            block = dict(block)
            for key in ("start", "end"):
                moment = datetime.fromisoformat(str(block[key]))
                block[key] = (moment + offset).isoformat()
            shifted.append(block)
        seed_calendar["busy"] = shifted
    return dataclasses.replace(scenario, seed_calendar=seed_calendar)


def build_corpus_a(
    root: Path | None = None,
    *,
    seed: int = DEFAULT_CORPUS_SEED,
    variants: int = DEFAULT_VARIANTS,
    agents: tuple[str, ...] = tuple(AGENT_FILES),
) -> list[Trace]:
    """Run every scenario with every agent and variant; return traces.

    Order is deterministic: packs and scenarios in loader order, then
    agents in the given order, then variant index.
    """
    root = root if root is not None else default_qualbench_root()
    qb = load_qualbench(root)
    traces: list[Trace] = []
    for pack in qb.discover_packs(root / "packs"):
        for scenario in pack.scenarios:
            group_id = group_id_for(scenario)
            for agent_name in agents:
                for variant in range(variants):
                    variant_rng = random.Random(
                        trace_seed_for(seed, group_id, agent_name, variant)
                    )
                    perturbed = perturb_scenario(scenario, variant, variant_rng)
                    traces.append(
                        run_and_emit(
                            root,
                            perturbed,
                            agent_name,
                            variant=variant,
                            corpus_seed=seed,
                        )
                    )
    return traces


def group_of(trace: Trace) -> str:
    """Recover a trace's split group from its stable trace id."""
    return trace.trace_id.rsplit(":", 2)[0]


def split_traces(
    traces: list[Trace], *, seed: int = DEFAULT_CORPUS_SEED
) -> dict[str, list[Trace]]:
    """Group-aware 80/10/10 split by trace, with a fixed seed.

    Groups are shuffled by the seed and cut 80/10/10 by count; every
    trace follows its group. Returns {train, validation, test} lists
    in corpus order.
    """
    groups = sorted({group_of(trace) for trace in traces})
    shuffled = list(groups)
    random.Random(seed).shuffle(shuffled)
    n_train = int(0.8 * len(shuffled))
    n_validation = int(0.1 * len(shuffled))
    assignment: dict[str, str] = {}
    for index, group in enumerate(shuffled):
        if index < n_train:
            assignment[group] = "train"
        elif index < n_train + n_validation:
            assignment[group] = "validation"
        else:
            assignment[group] = "test"
    splits: dict[str, list[Trace]] = {name: [] for name in SPLIT_NAMES}
    for trace in traces:
        splits[assignment[group_of(trace)]].append(trace)
    return splits


def _latency_table() -> list[str]:
    lines = [
        "| Vertical | instant | fast | slow | delayed | overnight |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for vertical, bands in LATENCY_DISTRIBUTIONS.items():
        weights = {band: weight for band, weight in bands}
        row = " | ".join(
            f"{weights[band]:.0%}"
            for band in ("instant", "fast", "slow", "delayed", "overnight")
        )
        lines.append(f"| {vertical} | {row} |")
    return lines


def corpus_card(
    traces: list[Trace],
    splits: dict[str, list[Trace]],
    *,
    seed: int = DEFAULT_CORPUS_SEED,
    variants: int = DEFAULT_VARIANTS,
) -> str:
    """Build the corpus card (Markdown) from the traces themselves."""
    event_count = sum(len(trace.events) for trace in traces)
    token_count = sum(len(encode_trace(trace)) for trace in traces)
    per_source = Counter(trace.source for trace in traces)
    per_vertical = Counter(trace.vertical for trace in traces)
    per_agent = Counter(trace.agent for trace in traces)
    outcomes = Counter(trace.outcome for trace in traces)
    split_groups = {
        name: len({group_of(trace) for trace in splits[name]})
        for name in SPLIT_NAMES
    }
    lines = [
        "# Corpus card: WorkLang corpus source A (QualBench)",
        "",
        f"This corpus is {SYNTHETIC_SENTENCE}.",
        "",
        "Source A is generated by running the QualBench scenario packs "
        "through the unmodified QualBench runner with its two shipped "
        "agents and converting each run with the WorkLang QualBench "
        f"trace emitter ({EMITTER_NAME} {EMITTER_VERSION}).",
        "",
        "## Counts",
        "",
        f"- Traces: {len(traces)}",
        f"- Events: {event_count}",
        f"- Tokens: {token_count} (encoded trace length: BOS, one "
        "vertical token, 7 tokens per event, EOS)",
        "",
        "Per source:",
        "",
    ]
    for name in sorted(per_source):
        lines.append(f"- {name}: {per_source[name]} traces")
    lines += ["", "Per vertical:", ""]
    for name in sorted(per_vertical):
        lines.append(f"- {name}: {per_vertical[name]} traces")
    lines += ["", "Per agent:", ""]
    for name in sorted(per_agent):
        lines.append(f"- {name}: {per_agent[name]} traces")
    lines += ["", "Outcome distribution (trace level outcome class):", ""]
    for name in sorted(outcomes):
        lines.append(f"- {name}: {outcomes[name]} traces")
    lines += [
        "",
        "## Variants",
        "",
        f"Each scenario is run {variants} time(s) per agent: the "
        "scenario as shipped (variant 0) plus seeded variants. A "
        "variant shifts every seeded calendar busy block of the "
        "scenario by one seeded whole-hour offset, preserving layout; "
        "expected outcomes are never edited, and every variant is a "
        "real run through the unmodified runner. Names, budgets, and "
        "requested times live inside prose turns and are not perturbed "
        "in v0, because the scenario loader exposes them only as "
        "opaque strings.",
        "",
        "## Splits",
        "",
        "Group-aware split by trace, 80/10/10 train/validation/test. "
        "A group is one scenario across both agents and all variants; "
        "no group appears in two splits.",
        "",
        f"- Split seed: {seed}",
    ]
    for name in SPLIT_NAMES:
        lines.append(
            f"- {name}: {len(splits[name])} traces "
            f"({split_groups[name]} groups)"
        )
    lines += [
        "",
        "## Latency declaration",
        "",
        "Latency values in this corpus are generator-declared, not "
        "measured. Neither simulator emits inter-event timing, so the "
        "emitter declares the gap before each event by drawing from "
        "the per-vertical distributions below, with the trace's seeded "
        "generator. The first event of every trace carries latency "
        '"none" (it has no predecessor).',
        "",
        *_latency_table(),
        "",
        "## Channels",
        "",
        "QualBench scenarios declare no channel, so every event in "
        "this corpus carries channel \"unknown\" rather than an "
        "invented one.",
        "",
        "## Known schema gap",
        "",
        "QualBench agents report two stage strings with no token in "
        "the WorkLang stage vocabulary (the ten LeadPipe stages plus "
        "none): HANDOFF and UNQUALIFIED. Neither is silently mapped "
        "into the stage stream. HANDOFF coincides with the handoff "
        "flag and surfaces as handoff events; a run whose final stage "
        "is UNQUALIFIED closes with outcome \"lost\". Whether these "
        "deserve stage tokens is a schema v2 question, recorded in "
        "DESIGN.md.",
        "",
        "## Provenance",
        "",
        f"- Generator: {EMITTER_NAME} {EMITTER_VERSION}, corpus seed {seed}",
        f"- Sentence required wherever this corpus is described: "
        f"\"{SYNTHETIC_SENTENCE}\"",
        "",
    ]
    return "\n".join(lines)


def write_corpus(
    out_dir: Path,
    traces: list[Trace],
    splits: dict[str, list[Trace]],
    card: str,
) -> dict[str, Path]:
    """Write the full corpus, the split files, and the corpus card."""
    out_dir.mkdir(parents=True, exist_ok=True)
    paths: dict[str, Path] = {}

    def _write_jsonl(name: str, rows: list[Trace]) -> Path:
        path = out_dir / name
        path.write_text(
            "".join(trace_to_json(trace) + "\n" for trace in rows),
            encoding="utf-8",
        )
        return path

    paths["corpus"] = _write_jsonl("corpus-a.jsonl", traces)
    for name in SPLIT_NAMES:
        paths[name] = _write_jsonl(f"corpus-a-{name}.jsonl", splits[name])
    card_path = out_dir / "CORPUS_CARD.md"
    card_path.write_text(card, encoding="utf-8")
    paths["card"] = card_path
    return paths


def load_corpus_file(path: Path) -> list[Trace]:
    """Read a corpus JSONL file back into validated traces."""
    from .schema import trace_from_json

    return [
        trace_from_json(line)
        for line in path.read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]


def corpus_summary_json(traces: list[Trace]) -> str:
    """Machine-readable counts, for callers that do not want Markdown."""
    return json.dumps(
        {
            "traces": len(traces),
            "events": sum(len(trace.events) for trace in traces),
            "tokens": sum(len(encode_trace(trace)) for trace in traces),
            "outcomes": dict(Counter(trace.outcome for trace in traces)),
        },
        indent=2,
        sort_keys=True,
    )
